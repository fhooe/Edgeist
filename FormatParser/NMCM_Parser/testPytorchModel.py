import numpy as np
import torch
import torch.nn as nn


class SimpleNN(nn.Module):
    def __init__(self):
        super(SimpleNN, self).__init__()

        # (1, 28, 28)
        self.conv1 = nn.Conv2d(1, 6, kernel_size=5, padding=2)  # → (6, 28, 28)
        self.bn1 = nn.BatchNorm2d(6)
        self.relu1 = nn.ReLU()
        self.pool1 = nn.MaxPool2d(2, 2)  # → (6, 14, 14)

        self.conv2 = nn.Conv2d(6, 12, kernel_size=5, padding=2)  # → (12, 14, 14)
        self.bn2 = nn.BatchNorm2d(12)
        self.relu2 = nn.ReLU()
        self.pool2 = nn.MaxPool2d(2, 2)  # → (12, 7, 7)

        self.adaptive_pool2d = nn.AdaptiveAvgPool2d((3, 3))  # → (12, 3, 3)

        self.flatten = nn.Flatten()  # → 12*3*3 = 108
        self.fc1 = nn.Linear(108, 32)
        self.bn3 = nn.BatchNorm1d(32)
        self.relu3 = nn.ReLU()
        self.dropout = nn.Dropout(p=0.25)

        self.adaptive_pool1d = nn.AdaptiveAvgPool1d(10)  # → (32 → 10)

        self.fc2 = nn.Linear(10, 10)

    def forward(self, x):
        x = self.pool1(self.relu1(self.bn1(self.conv1(x))))
        x = self.pool2(self.relu2(self.bn2(self.conv2(x))))
        x = self.adaptive_pool2d(x)
        x = self.flatten(x)
        x = self.dropout(self.relu3(self.bn3(self.fc1(x))))
        x = self.adaptive_pool1d(x.unsqueeze(0)).squeeze(0)
        x = self.fc2(x)
        return x


